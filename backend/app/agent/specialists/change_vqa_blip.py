"""External BLIP Change-VQA specialist (Phase 14 integration).

Wraps the already-trained external checkpoint at ``change_model/`` (a
``BlipForQuestionAnswering`` model fine-tuned on CDVQA) as a uniform specialist. It is a
**generative single-image** VQA model: given an image and a question it generates a short
answer. For a T1/T2 pair it presents one image under the frozen ``t1`` convention
determined on CDVQA validation only (see ``ml.inference.change_model_infer`` and
``reports/change_model``).

Honesty:
- It is integrated as an ADDITIONAL Change-VQA specialist, NOT as the default. The
  deterministic measurement-grounded ``change_vqa`` remains the default route.
- It is truthfully a single-image model; no fake two-image temporal input is claimed.
- On the CDVQA held-out benchmark it scored Test 0.5467 / Test2 0.5033 - BELOW the
  project's own ``cdvqa_trained`` (0.7114 / 0.6632). That is surfaced as a warning.
- The weights are loaded read-only; nothing is retrained.
"""

from __future__ import annotations

from ..types import EvidenceItem, SpecialistResult
from .base import Specialist, SpecialistContext, SpecialistUnavailable
from .vision_support import load_asset_image, model_evidence, preview_evidence


class ChangeVQABlipSpecialist(Specialist):
    tool_id = "change_vqa_blip"

    def run(self, context: SpecialistContext) -> SpecialistResult:
        from ml.inference import change_model_infer

        status = change_model_infer.availability()
        if not status.available:
            raise SpecialistUnavailable(self.tool_id, status.reason)

        assets = context.assets()
        if not assets:
            return SpecialistResult(
                answer="No readable image was found for this request.",
                warnings=["The referenced upload could not be loaded."],
            )

        question = context.query.strip() or "What has changed?"

        try:
            if len(assets) >= 2:
                t1 = load_asset_image(assets[0]).image
                t2 = load_asset_image(assets[1]).image
                pred = change_model_infer.predict_pair(t1, t2, question)
                pair_note = (
                    f"single-image BLIP applied to the T1/T2 pair via the frozen "
                    f"'{pred.convention}' convention (selected on CDVQA validation only)"
                )
            else:
                img = load_asset_image(assets[0]).image
                pred = change_model_infer.predict_single(img, question)
                pair_note = "single image"
        except Exception as exc:  # noqa: BLE001 - surfaced as a specialist warning
            return SpecialistResult(
                answer="The image could not be read for analysis.",
                warnings=[f"Raster read failed: {type(exc).__name__}."],
            )

        conf_text = (
            f" (generation confidence {pred.confidence:.2f}, uncalibrated)"
            if pred.confidence is not None
            else ""
        )
        answer = (
            f"The trained Change-VQA model (external BLIP) answers: \"{pred.answer}\"{conf_text}."
        )

        evidence: list[EvidenceItem] = [
            EvidenceItem(
                kind="model",
                label="Trained Change-VQA model (external BLIP)",
                detail={
                    "model_id": "change_vqa_blip",
                    "architecture": "BlipForQuestionAnswering (single-image, 384px, generative)",
                    "checkpoint": "change_model/model.safetensors",
                    "version": pred.model_version,
                    "device": pred.device,
                    "raw_generation": pred.raw,
                    "pair_presentation": pair_note,
                    "training_dataset": "CDVQA (external fine-tune; not trained by this project)",
                    "benchmark": "CDVQA held-out Test 0.5467 / Test2 0.5033 (n=600 each)",
                    "note": (
                        "Generative single-image VQA. Confidence is an uncalibrated mean "
                        "token probability, not a probability of correctness."
                    ),
                },
            ),
            *preview_evidence(assets[0]),
            model_evidence(
                "change_vqa_blip",
                pred.device,
                "External BLIP checkpoint fine-tuned on CDVQA; answer generated, not composed.",
            ),
        ]

        warnings = [
            "This answer was generated by the external BLIP Change-VQA checkpoint "
            "(change_model/), a single-image generative model. On the CDVQA held-out "
            "benchmark it scored Test 0.5467 / Test2 0.5033, BELOW the project's own "
            "cdvqa_trained (0.7114 / 0.6632).",
            f"BLIP sees one image; for a temporal pair it uses the {pair_note}.",
            "The confidence shown is an uncalibrated generation score, not a probability "
            "of correctness.",
        ]

        return SpecialistResult(
            answer=answer,
            score=pred.confidence,
            evidence=evidence,
            details={
                "model_id": "change_vqa_blip",
                "answer_token": pred.answer,
                "raw": pred.raw,
                "convention": pred.convention,
                "generation_confidence": pred.confidence,
            },
            warnings=warnings,
        )
