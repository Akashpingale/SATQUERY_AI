"""External BLIP captioning specialist.

Wraps a trained external checkpoint at ``caption_model/`` (a
``BlipForConditionalGeneration`` model fine-tuned on VRSBench) as a uniform specialist. It is
a **generative single-image** captioner: given an image it generates a free-text description
word by word.

Honesty:
- It is integrated as an ADDITIONAL captioning specialist, alongside the existing CLIP-based
  ``captioning`` specialist (which composes text from concept scores, not generation).
- No benchmarked accuracy is claimed; training loss curves are the only measurement we have.
- The weights are loaded read-only; nothing is retrained.
"""

from __future__ import annotations

from ..types import EvidenceItem, SpecialistResult
from .base import Specialist, SpecialistContext, SpecialistUnavailable
from .vision_support import load_asset_image, model_evidence, preview_evidence


class CaptioningBlipSpecialist(Specialist):
    tool_id = "captioning_blip"

    def run(self, context: SpecialistContext) -> SpecialistResult:
        from ml.inference import caption_model_infer

        status = caption_model_infer.availability()
        if not status.available:
            raise SpecialistUnavailable(self.tool_id, status.reason)

        assets = context.assets()
        if not assets:
            return SpecialistResult(
                answer="No readable image was found for this request.",
                warnings=["The referenced upload could not be loaded."],
            )

        try:
            img = load_asset_image(assets[0]).image
            pred = caption_model_infer.predict(img)
        except Exception as exc:  # noqa: BLE001 - surfaced as a specialist warning
            return SpecialistResult(
                answer="The image could not be read for analysis.",
                warnings=[f"Raster read failed: {type(exc).__name__}."],
            )

        conf_text = (
            f" (generation confidence {pred.confidence:.2f}, uncalibrated)"
            if pred.confidence is not None
            else ""
        )
        answer = f"{pred.caption}{conf_text}"

        evidence: list[EvidenceItem] = [
            EvidenceItem(
                kind="model",
                label="Trained captioning model (external BLIP)",
                detail={
                    "model_id": "captioning_blip",
                    "architecture": "BlipForConditionalGeneration (single-image, generative)",
                    "checkpoint": "caption_model/model.safetensors",
                    "version": pred.model_version,
                    "device": pred.device,
                    "raw_generation": pred.raw,
                    "training_dataset": "VRSBench (external fine-tune by this team)",
                    "note": (
                        "Generative single-image captioning. Confidence is an uncalibrated "
                        "mean token probability, not a probability of correctness. No "
                        "benchmarked accuracy has been measured for this checkpoint."
                    ),
                },
            ),
            *preview_evidence(assets[0]),
            model_evidence(
                "captioning_blip",
                pred.device,
                "External BLIP checkpoint fine-tuned on VRSBench; caption generated, not composed.",
            ),
        ]

        warnings = [
            "This caption was generated by the external BLIP captioning checkpoint "
            "(caption_model/), a single-image generative model fine-tuned on VRSBench.",
            "The confidence shown is an uncalibrated generation score, not a probability "
            "of correctness.",
            "No benchmarked accuracy has been measured for this checkpoint; only training "
            "loss curves are available.",
        ]

        return SpecialistResult(
            answer=answer,
            score=pred.confidence,
            evidence=evidence,
            details={
                "model_id": "captioning_blip",
                "caption": pred.caption,
                "raw": pred.raw,
                "generation_confidence": pred.confidence,
            },
            warnings=warnings,
        )
